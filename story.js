function saveGame() {
    const saveData = {
        time: gameState.time,
        trust: gameState.trust,
        clues: gameState.clues,
        stress: gameState.stress,
        guilt: gameState.guilt,
        redHerrings: gameState.redHerrings,
        currentScene: gameState.currentScene,
        magnusFree: gameState.magnusFree,
        lockArrest: gameState.lockArrest,
        won: gameState.won,
        betrayedBillMichael: gameState.betrayedBillMichael
    };
    localStorage.setItem('lastCrossSave', JSON.stringify(saveData));
}

function loadGame() {
    const saved = localStorage.getItem('lastCrossSave');
    if (saved) {
        try {
            const data = JSON.parse(saved);
            gameState.time = data.time || 0;
            gameState.trust = data.trust || 5;
            gameState.clues = data.clues || [];
            gameState.stress = data.stress || 0;
            gameState.guilt = data.guilt || 0;
            gameState.redHerrings = data.redHerrings || 0;
            gameState.currentScene = data.currentScene || 'scene0_flashback';
            gameState.magnusFree = data.magnusFree !== undefined ? data.magnusFree : null;
            gameState.lockArrest = data.lockArrest || false;
            gameState.won = data.won !== undefined ? data.won : null;
            gameState.betrayedBillMichael = data.betrayedBillMichael !== undefined ? data.betrayedBillMichael : null;
            return true;
        } catch(e) {
            console.error('Load failed:', e);
            return false;
        }
    }
    return false;
}

window.onload = function() {
    if (loadGame()) {
        loadScene(gameState.currentScene);
    } else {
        loadScene('scene0_flashback');
    }
};






